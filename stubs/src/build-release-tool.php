<?php

/**
 * Builds stubs/slipstream-release.php: the framework-free classes under
 * src/Release/Core, followed by stubs/src/release-main.php, in one file. The
 * stub is committed so an image can carry it; `composer stub:build`
 * regenerates it, and a test fails when the committed copy is out of date.
 */
function slipstream_release_tool_source(): string
{
    $root = dirname(__DIR__, 2);
    $files = glob($root.'/src/Release/Core/*.php') ?: [];
    sort($files, SORT_STRING);

    // Interfaces before the classes that implement them: PHP declares a
    // class whose interface is not yet known only at run time, if at all.
    usort($files, fn (string $a, string $b) => (basename($a) === 'Signer.php' ? 0 : 1) <=> (basename($b) === 'Signer.php' ? 0 : 1) ?: strcmp($a, $b));

    $normalize = fn (string $code) => str_replace(["\r\n", "\r"], "\n", $code);

    $bodies = [];
    foreach ($files as $file) {
        $code = $normalize((string) file_get_contents($file));
        $code = (string) preg_replace('/^<\?php\s*/', '', $code);
        $code = (string) preg_replace('/^namespace\s+[^;]+;\s*/m', '', $code);
        $code = (string) preg_replace('/^use\s+[^;]+;\s*$/m', '', $code);
        $bodies[] = '// — '.basename($file)."\n\n".trim($code);
    }

    $main = $normalize((string) file_get_contents(__DIR__.'/release-main.php'));
    $main = trim((string) preg_replace('/^<\?php\s*/', '', $main));

    return "<?php\n\n"
        ."/*\n"
        ." * slipstream-release.php — GENERATED by `composer stub:build` from src/Release/Core\n"
        ." * and stubs/src/release-main.php. Do not edit; edit those and rebuild.\n"
        ." *\n"
        ." * A single file with no dependencies beyond PHP's sodium, zlib and hash\n"
        ." * extensions: verifies and unpacks a release on a node that has no\n"
        ." * Slipstream code yet (slipstream-bootstrap.sh), and signs and publishes\n"
        ." * one from CI without installing or booting anything.\n"
        ." */\n\n"
        ."namespace Slipstream\\Release\\Core {\n\n"
        .implode("\n\n", $bodies)
        ."\n\n}\n\n"
        ."namespace {\n\n"
        .$main
        ."\n\n}\n";
}

if (PHP_SAPI === 'cli' && isset($argv[0]) && realpath($argv[0]) === __FILE__) {
    $target = dirname(__DIR__).'/slipstream-release.php';
    file_put_contents($target, slipstream_release_tool_source());
    echo 'wrote '.$target."\n";
}
